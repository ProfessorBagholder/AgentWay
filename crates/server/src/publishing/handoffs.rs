fn valid_text(value: &str, max: usize) -> bool {
    !value.trim().is_empty()
        && value.len() <= max
        && !value
            .chars()
            .any(|c| c.is_control() && c != '\n' && c != '\t')
}
fn claim_digest(token: &str) -> String {
    format!("{:x}", Sha256::digest(token.as_bytes()))
}

impl Publisher {
    pub(super) async fn handoff_deadline_worker(&self) {
        let mut interval = tokio::time::interval(Duration::from_secs(5));
        loop {
            tokio::select! {
                _ = self.0.shutdown.cancelled() => return,
                _ = interval.tick() => {
                    if let Err(error) = self.expire_handoffs().await {
                        tracing::error!(%error, "Could not expire agent handoffs");
                    }
                }
            }
        }
    }
    pub(super) async fn discover_agents(&self) -> Result<Value> {
        let rows: Vec<(String, String, String)> = sqlx::query_as(
            "SELECT c.id,c.name,c.product FROM agent_handoff_grants g JOIN agent_connections c ON c.id=g.recipient_id WHERE g.sender_id=? AND c.disconnected=0 ORDER BY c.name,c.id")
            .bind(self.connection_id()).fetch_all(&self.0.db).await?;
        Ok(json!(rows.into_iter().map(|(id,name,product)| json!({"id":id,"name":name,"product":product,"delivery":"inbox"})).collect::<Vec<_>>()))
    }
    pub(super) async fn create_handoff(&self, input: CreateHandoff) -> Result<Value> {
        Uuid::parse_str(&input.request_id)?;
        if !valid_text(&input.title, 200) || !valid_text(&input.instructions, 16_000) {
            bail!("Task title or instructions are empty or too long");
        }
        let timeout = input.timeout_seconds.unwrap_or(DEFAULT_TIMEOUT_SECONDS);
        if !(MIN_TIMEOUT_SECONDS..=MAX_TIMEOUT_SECONDS).contains(&timeout) {
            bail!("timeout_seconds must be between 60 and 604800");
        }
        if self.connection_id() == input.recipient_id {
            bail!("Choose another agent");
        }
        self.expire_handoffs().await?;
        let _guard = self.0.mutation.lock().await;
        let mut tx = self.0.db.begin().await?;
        if let Some(existing) = sqlx::query_as::<_, Handoff>(
            "SELECT rowid AS cursor,* FROM agent_handoffs WHERE sender_id=? AND request_id=?",
        )
        .bind(self.connection_id())
        .bind(&input.request_id)
        .fetch_optional(&mut *tx)
        .await?
        {
            if existing.recipient_id != input.recipient_id
                || existing.title != input.title
                || existing.instructions != input.instructions
                || (existing.timeout_seconds.is_some() && existing.timeout_seconds != Some(timeout))
                || (existing.timeout_seconds.is_none() && input.timeout_seconds.is_some())
                || (existing.delivery_mode == "automatic") != input.automatic_delivery
            {
                return Err(conflict("request_id already belongs to a different task"));
            }
            return Ok(serde_json::to_value(existing)?);
        }
        let sender: (String,) =
            sqlx::query_as("SELECT name FROM agent_connections WHERE id=? AND disconnected=0")
                .bind(self.connection_id())
                .fetch_one(&mut *tx)
                .await?;
        let recipient: Option<(String,)> = sqlx::query_as(
            "SELECT c.name FROM agent_handoff_grants g JOIN agent_connections c ON c.id=g.recipient_id WHERE g.sender_id=? AND g.recipient_id=? AND c.disconnected=0")
            .bind(self.connection_id()).bind(&input.recipient_id).fetch_optional(&mut *tx).await?;
        let recipient =
            recipient.ok_or_else(|| forbidden("Recipient is not available or permitted"))?;
        let binding_generations = if input.automatic_delivery {
            let generations: Vec<(String, i64)> = sqlx::query_as(
                "SELECT b.connection_id,b.generation FROM handoff_receiver_bindings b JOIN agent_connections c ON c.id=b.connection_id WHERE b.connection_id IN (?,?) AND b.enabled=1 AND b.verified_at IS NOT NULL AND b.proof_expires_at>unixepoch() AND c.disconnected=0",
            )
            .bind(self.connection_id())
            .bind(&input.recipient_id)
            .fetch_all(&mut *tx)
            .await?;
            if generations.len() != 2 {
                return Err(conflict("Automatic handoff receiver is unavailable"));
            }
            let sender_generation = generations
                .iter()
                .find(|(id, _)| id == self.connection_id())
                .map(|(_, generation)| *generation)
                .ok_or_else(|| conflict("Automatic handoff sender is unavailable"))?;
            let recipient_generation = generations
                .iter()
                .find(|(id, _)| id == &input.recipient_id)
                .map(|(_, generation)| *generation)
                .ok_or_else(|| conflict("Automatic handoff receiver is unavailable"))?;
            Some((sender_generation, recipient_generation))
        } else {
            None
        };
        let id = Uuid::new_v4().to_string();
        sqlx::query("INSERT INTO agent_handoffs(id,request_id,sender_id,sender_name,recipient_id,recipient_name,title,instructions,timeout_seconds,expires_at,delivery_mode,sender_binding_generation,recipient_binding_generation) VALUES(?,?,?,?,?,?,?,?,?,unixepoch()+?,?,?,?)")
            .bind(&id).bind(&input.request_id).bind(self.connection_id()).bind(sender.0)
            .bind(&input.recipient_id).bind(recipient.0).bind(&input.title).bind(&input.instructions)
            .bind(timeout).bind(timeout)
            .bind(if input.automatic_delivery { "automatic" } else { "pull" })
            .bind(binding_generations.map(|(sender, _)| sender))
            .bind(binding_generations.map(|(_, recipient)| recipient))
            .execute(&mut *tx).await?;
        let row = Self::handoff_in_tx(&mut tx, &id).await?;
        Self::handoff_event(&mut tx, &row, "created").await?;
        if let Some((_, recipient_generation)) = binding_generations {
            Self::handoff_delivery(
                &mut tx,
                &row,
                "task_offered",
                &row.recipient_id,
                recipient_generation,
            )
            .await?;
        }
        tx.commit().await?;
        Ok(serde_json::to_value(row)?)
    }
    async fn handoff_in_tx(tx: &mut Transaction<'_, Sqlite>, id: &str) -> Result<Handoff> {
        Ok(
            sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE id=?")
                .bind(id)
                .fetch_one(&mut **tx)
                .await?,
        )
    }
    async fn handoff_event(
        tx: &mut Transaction<'_, Sqlite>,
        row: &Handoff,
        action: &str,
    ) -> Result<()> {
        let mut payload = serde_json::to_value(row)?;
        payload["action"] = json!(action);
        sqlx::query("INSERT INTO events(kind,payload) VALUES('agent.handoff',?)")
            .bind(payload.to_string())
            .execute(&mut **tx)
            .await?;
        Ok(())
    }
    async fn handoff_delivery(
        tx: &mut Transaction<'_, Sqlite>,
        row: &Handoff,
        kind: &str,
        connection_id: &str,
        generation: i64,
    ) -> Result<()> {
        let expires_at = if kind == "task_offered" {
            row.expires_at
                .ok_or_else(|| conflict("Automatic task has no deadline"))?
        } else {
            // Return delivery has its own finite window after the task becomes terminal.
            sqlx::query_scalar::<_, i64>("SELECT unixepoch()+?")
                .bind(RESULT_DELIVERY_SECONDS)
                .fetch_one(&mut **tx)
                .await?
        };
        sqlx::query("INSERT INTO handoff_delivery_outbox(id,task_id,kind,connection_id,binding_generation,expires_at) VALUES(?,?,?,?,?,?)")
            .bind(Uuid::new_v4().to_string()).bind(&row.id).bind(kind).bind(connection_id)
            .bind(generation).bind(expires_at).execute(&mut **tx).await?;
        Ok(())
    }
    async fn enqueue_result_delivery(
        tx: &mut Transaction<'_, Sqlite>,
        row: &Handoff,
    ) -> Result<()> {
        if row.delivery_mode == "automatic" {
            let generation = row
                .sender_binding_generation
                .ok_or_else(|| conflict("Automatic task has no sender binding"))?;
            Self::handoff_delivery(tx, row, "result_available", &row.sender_id, generation).await?;
        }
        Ok(())
    }
    /// Materialize elapsed deadlines in the same transaction as their audit events.
    /// Called by the independent sweeper and before reads; late writes are fenced in SQL.
    pub(super) async fn expire_handoffs(&self) -> Result<usize> {
        let mut total = 0;
        loop {
            let mut tx = self.0.db.begin().await?;
            // The first statement writes, avoiding a deferred read transaction that
            // could become a stale SQLite snapshot under concurrent API traffic.
            let ids: Vec<String> = sqlx::query_scalar("UPDATE agent_handoffs SET status='timed_out',error=CASE WHEN status='queued' THEN 'Recipient did not claim the task before its deadline.' ELSE 'Task deadline passed after claim; external effects may be unknown.' END,claim_hash=NULL,lease_until=NULL,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id IN (SELECT id FROM agent_handoffs WHERE status IN ('queued','claimed') AND expires_at IS NOT NULL AND expires_at<=unixepoch() ORDER BY expires_at LIMIT 100) AND status IN ('queued','claimed') AND expires_at<=unixepoch() RETURNING id")
            .fetch_all(&mut *tx)
            .await?;
            let batch_size = ids.len();
            for id in ids {
                let row = Self::handoff_in_tx(&mut tx, &id).await?;
                Self::handoff_event(&mut tx, &row, "timed_out").await?;
                Self::enqueue_result_delivery(&mut tx, &row).await?;
            }
            tx.commit().await?;
            total += batch_size;
            if batch_size < 100 {
                return Ok(total);
            }
        }
    }
    pub(super) async fn list_handoffs(
        &self,
        status: Option<&str>,
        before: Option<i64>,
        owner: bool,
    ) -> Result<Value> {
        if let Some(s) = status
            && ![
                "queued",
                "claimed",
                "completed",
                "failed",
                "cancelled",
                "timed_out",
            ]
            .contains(&s)
        {
            bail!("Invalid status");
        }
        self.expire_handoffs().await?;
        let before = before.unwrap_or(i64::MAX);
        if before < 1 {
            bail!("Invalid cursor");
        }
        let mut rows: Vec<Handoff> = if owner {
            sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE rowid<? AND (? IS NULL OR status=?) ORDER BY rowid DESC LIMIT 101")
                .bind(before).bind(status).bind(status).fetch_all(&self.0.db).await?
        } else {
            sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE rowid<? AND (sender_id=? OR recipient_id=?) AND (? IS NULL OR status=?) ORDER BY rowid DESC LIMIT 101")
                .bind(before).bind(self.connection_id()).bind(self.connection_id()).bind(status).bind(status).fetch_all(&self.0.db).await?
        };
        let next = if rows.len() > 100 {
            rows.truncate(100);
            rows.last().map(|row| row.cursor)
        } else {
            None
        };
        Ok(json!({"items":rows,"next":next}))
    }
    pub(super) async fn get_handoff(&self, id: &str, owner: bool) -> Result<Value> {
        self.expire_handoffs().await?;
        let row: Option<Handoff> =
            sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE id=?")
                .bind(id)
                .fetch_optional(&self.0.db)
                .await?;
        let row = row
            .filter(|r| {
                owner
                    || r.sender_id == self.connection_id()
                    || r.recipient_id == self.connection_id()
            })
            .ok_or_else(missing)?;
        Ok(serde_json::to_value(row)?)
    }
    async fn handoff_history(&self, id: &str, after: i64) -> Result<Value> {
        self.get_handoff(id, true).await?;
        if after < 0 {
            bail!("Invalid cursor");
        }
        let rows:Vec<(i64,String)>=sqlx::query_as("SELECT sequence,payload FROM events WHERE kind='agent.handoff' AND json_extract(payload,'$.id')=? AND sequence>? ORDER BY sequence LIMIT 101")
            .bind(id).bind(after).fetch_all(&self.0.db).await?;
        let has_more = rows.len() > 100;
        let mut items = Vec::new();
        for (sequence, payload) in rows.into_iter().take(100) {
            items
                .push(json!({"sequence":sequence,"task":serde_json::from_str::<Value>(&payload)?}));
        }
        let next = if has_more {
            items.last().and_then(|v| v["sequence"].as_i64())
        } else {
            None
        };
        Ok(json!({"items":items,"next":next}))
    }
    pub(super) async fn claim_handoff(&self, id: &str, token: &str) -> Result<Value> {
        if Uuid::parse_str(token)?.get_version_num() != 4 {
            bail!("claim_token must be a random UUID v4");
        }
        let hash = claim_digest(token);
        let _guard = self.0.mutation.lock().await;
        let mut tx = self.0.db.begin().await?;
        let prior: Option<Handoff> = sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE id=? AND recipient_id=? AND status='claimed' AND lease_until>=unixepoch() AND (expires_at IS NULL OR expires_at>unixepoch()) AND claim_hash=?")
            .bind(id).bind(self.connection_id()).bind(&hash).fetch_optional(&mut *tx).await?;
        if let Some(prior) = prior {
            let mut value = serde_json::to_value(prior)?;
            value["claim_token"] = json!(token);
            return Ok(value);
        }
        let changed = sqlx::query(
            "UPDATE agent_handoffs SET status='claimed',claim_hash=?,lease_until=unixepoch()+?,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id=? AND recipient_id=? AND (status='queued' OR (status='claimed' AND lease_until<unixepoch())) AND (expires_at IS NULL OR expires_at>unixepoch()) AND EXISTS(SELECT 1 FROM agent_connections WHERE id=? AND disconnected=0)")
            .bind(hash).bind(LEASE_SECONDS).bind(id).bind(self.connection_id()).bind(self.connection_id())
            .execute(&mut *tx).await?;
        if changed.rows_affected() != 1 {
            return Err(conflict("Task is not claimable"));
        }
        let row = Self::handoff_in_tx(&mut tx, id).await?;
        Self::handoff_event(&mut tx, &row, "claimed").await?;
        tx.commit().await?;
        let mut value = serde_json::to_value(row)?;
        value["claim_token"] = json!(token);
        Ok(value)
    }
    pub(super) async fn renew_handoff(&self, id: &str, token: &str) -> Result<Value> {
        let mut tx = self.0.db.begin().await?;
        let changed=sqlx::query("UPDATE agent_handoffs SET lease_until=unixepoch()+?,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id=? AND recipient_id=? AND status='claimed' AND lease_until>=unixepoch() AND (expires_at IS NULL OR expires_at>unixepoch()) AND claim_hash=?")
            .bind(LEASE_SECONDS).bind(id).bind(self.connection_id()).bind(claim_digest(token)).execute(&mut *tx).await?;
        if changed.rows_affected() != 1 {
            return Err(conflict("Claim expired or task is no longer active"));
        }
        let row = Self::handoff_in_tx(&mut tx, id).await?;
        Self::handoff_event(&mut tx, &row, "renewed").await?;
        tx.commit().await?;
        Ok(serde_json::to_value(row)?)
    }
    pub(super) async fn finish_handoff(
        &self,
        id: &str,
        input: FinishInput,
        failed: bool,
    ) -> Result<Value> {
        if !valid_text(&input.message, 16_000) {
            bail!("Result is empty or too long");
        }
        let mut tx = self.0.db.begin().await?;
        let changed=sqlx::query("UPDATE agent_handoffs SET status=?,result=?,error=?,claim_hash=NULL,lease_until=NULL,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id=? AND recipient_id=? AND status='claimed' AND lease_until>=unixepoch() AND (expires_at IS NULL OR expires_at>unixepoch()) AND claim_hash=?")
            .bind(if failed {"failed"}else{"completed"})
            .bind(if failed {None}else{Some(input.message.as_str())})
            .bind(if failed {Some(input.message.as_str())}else{None})
            .bind(id).bind(self.connection_id()).bind(claim_digest(&input.claim_token)).execute(&mut *tx).await?;
        if changed.rows_affected() != 1 {
            return Err(conflict("Claim expired or task is no longer active"));
        }
        let row = Self::handoff_in_tx(&mut tx, id).await?;
        Self::handoff_event(&mut tx, &row, if failed { "failed" } else { "completed" }).await?;
        Self::enqueue_result_delivery(&mut tx, &row).await?;
        tx.commit().await?;
        Ok(serde_json::to_value(row)?)
    }
    pub(super) async fn cancel_handoff(&self, id: &str) -> Result<Value> {
        self.expire_handoffs().await?;
        let mut tx = self.0.db.begin().await?;
        let changed=sqlx::query("UPDATE agent_handoffs SET status='cancelled',claim_hash=NULL,lease_until=NULL,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id=? AND sender_id=? AND status IN ('queued','claimed') AND (expires_at IS NULL OR expires_at>unixepoch())")
            .bind(id).bind(self.connection_id()).execute(&mut *tx).await?;
        if changed.rows_affected() != 1 {
            return Err(conflict("Task cannot be cancelled"));
        }
        let row = Self::handoff_in_tx(&mut tx, id).await?;
        Self::handoff_event(&mut tx, &row, "cancelled").await?;
        Self::enqueue_result_delivery(&mut tx, &row).await?;
        tx.commit().await?;
        Ok(serde_json::to_value(row)?)
    }
    pub(super) async fn acknowledge_handoff_result(&self, id: &str) -> Result<Value> {
        self.expire_handoffs().await?;
        let _guard = self.0.mutation.lock().await;
        let mut tx = self.0.db.begin().await?;
        let changed = sqlx::query("UPDATE agent_handoffs SET result_acknowledged_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),revision=revision+1 WHERE id=? AND sender_id=? AND status IN ('completed','failed','cancelled','timed_out') AND result_acknowledged_at IS NULL AND EXISTS(SELECT 1 FROM agent_connections WHERE id=? AND disconnected=0)")
            .bind(id).bind(self.connection_id()).bind(self.connection_id())
            .execute(&mut *tx).await?;
        let row: Option<Handoff> =
            sqlx::query_as("SELECT rowid AS cursor,* FROM agent_handoffs WHERE id=?")
                .bind(id)
                .fetch_optional(&mut *tx)
                .await?;
        let row = row.ok_or_else(missing)?;
        if row.sender_id != self.connection_id() {
            return Err(missing());
        }
        if changed.rows_affected() == 1 {
            Self::handoff_event(&mut tx, &row, "result_acknowledged").await?;
        } else if row.result_acknowledged_at.is_none() {
            return Err(conflict("Task has no result to acknowledge"));
        }
        tx.commit().await?;
        Ok(serde_json::to_value(row)?)
    }
}
