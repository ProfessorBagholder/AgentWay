const LEASE_SECONDS: i64 = 300;
const DEFAULT_TIMEOUT_SECONDS: i64 = 86_400;
const MIN_TIMEOUT_SECONDS: i64 = 60;
const MAX_TIMEOUT_SECONDS: i64 = 604_800;
const RESULT_DELIVERY_SECONDS: i64 = 604_800;
#[derive(Debug)]
pub(super) struct HandoffError {
    pub status: StatusCode,
    pub message: &'static str,
}
impl std::fmt::Display for HandoffError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.message)
    }
}
impl std::error::Error for HandoffError {}
fn conflict(message: &'static str) -> anyhow::Error {
    HandoffError {
        status: StatusCode::CONFLICT,
        message,
    }
    .into()
}
fn forbidden(message: &'static str) -> anyhow::Error {
    HandoffError {
        status: StatusCode::FORBIDDEN,
        message,
    }
    .into()
}
fn missing() -> anyhow::Error {
    HandoffError {
        status: StatusCode::NOT_FOUND,
        message: "Task not found",
    }
    .into()
}

