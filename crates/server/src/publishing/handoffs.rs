    #[tokio::test]
    async fn permission_idempotency_claim_and_cancel() {
        let (_dir, p) = fixture().await;
        let sender = p.for_connection("sender");
        let receiver = p.for_connection("receiver");
        let stranger = p.for_connection("stranger");
        assert_eq!(sender.discover_agents().await.unwrap(), json!([]));
        let request_id = Uuid::new_v4().to_string();
        let input = || CreateHandoff {
            request_id: request_id.clone(),
            recipient_id: "receiver".into(),
            title: "Research".into(),
            instructions: "Review the facts".into(),
        };
        assert!(sender.create_handoff(input()).await.is_err());
        sqlx::query(
            "INSERT INTO agent_handoff_grants(sender_id,recipient_id) VALUES('sender','receiver')",
        )
        .execute(&p.0.db)
        .await
        .unwrap();
        assert_eq!(sender.discover_agents().await.unwrap()[0]["id"], "receiver");
        let created = sender.create_handoff(input()).await.unwrap();
        assert_eq!(sender.create_handoff(input()).await.unwrap(), created);
        assert_eq!(
            receiver
                .list_handoffs(Some("queued"), None, false)
                .await
                .unwrap()["items"][0]["id"],
            created["id"]
        );
        assert!(
            stranger
                .get_handoff(created["id"].as_str().unwrap(), false)
                .await
                .is_err()
        );
        assert!(
            stranger
                .claim_handoff(created["id"].as_str().unwrap(), &Uuid::new_v4().to_string())
                .await
                .is_err()
        );
        let id = created["id"].as_str().unwrap();
        let claim_token = Uuid::new_v4().to_string();
        let claim = receiver.claim_handoff(id, &claim_token).await.unwrap();
        assert_eq!(
            receiver.claim_handoff(id, &claim_token).await.unwrap(),
            claim
        );
        let token = claim["claim_token"].as_str().unwrap();
        assert!(
            sender
                .get_handoff(id, false)
                .await
                .unwrap()
                .get("claim_token")
                .is_none()
        );
        assert!(
            receiver
                .finish_handoff(
                    id,
                    FinishInput {
                        claim_token: "wrong".into(),
                        message: "Done".into()
                    },
                    false
                )
                .await
                .is_err()
        );
        sender.cancel_handoff(id).await.unwrap();
        assert!(
            receiver
                .finish_handoff(
                    id,
                    FinishInput {
                        claim_token: token.into(),
                        message: "Done".into()
                    },
                    false
                )
                .await
                .is_err()
        );
        assert_eq!(
            sender.get_handoff(id, false).await.unwrap()["status"],
            "cancelled"
        );
        receiver.disconnect_connection().await.unwrap();
        assert_eq!(sender.discover_agents().await.unwrap(), json!([]));
    }
    #[tokio::test]
    async fn completion_is_durable_and_stale_claim_is_fenced() {
        let (_dir, p) = fixture().await;
        sqlx::query(
            "INSERT INTO agent_handoff_grants(sender_id,recipient_id) VALUES('sender','receiver')",
        )
        .execute(&p.0.db)
        .await
        .unwrap();
        let sender = p.for_connection("sender");
        let receiver = p.for_connection("receiver");
        let row = sender
            .create_handoff(CreateHandoff {
                request_id: Uuid::new_v4().to_string(),
                recipient_id: "receiver".into(),
                title: "Check".into(),
                instructions: "Check this".into(),
            })
            .await
            .unwrap();
        let id = row["id"].as_str().unwrap();
        let first = receiver
            .claim_handoff(id, &Uuid::new_v4().to_string())
            .await
            .unwrap();
        sqlx::query("UPDATE agent_handoffs SET lease_until=unixepoch()-1 WHERE id=?")
            .bind(id)
            .execute(&p.0.db)
            .await
            .unwrap();
        let second = receiver
            .claim_handoff(id, &Uuid::new_v4().to_string())
            .await
            .unwrap();
        assert_ne!(first["claim_token"], second["claim_token"]);
        assert!(
            receiver
                .finish_handoff(
                    id,
                    FinishInput {
                        claim_token: first["claim_token"].as_str().unwrap().into(),
                        message: "Late".into()
                    },
                    false
                )
                .await
                .is_err()
        );
        let done = receiver
            .finish_handoff(
                id,
                FinishInput {
                    claim_token: second["claim_token"].as_str().unwrap().into(),
                    message: "Verified".into(),
                },
                false,
            )
            .await
            .unwrap();
        assert_eq!(done["status"], "completed");
        assert_eq!(
            sender.get_handoff(id, false).await.unwrap()["result"],
            "Verified"
        );
        let history = sender.handoff_history(id, 0).await.unwrap();
        assert_eq!(history["items"].as_array().unwrap().len(), 4);
        assert_eq!(history["items"][0]["task"]["action"], "created");
        assert_eq!(history["items"][3]["task"]["action"], "completed");
        assert!(!history.to_string().contains("claim_token"));
        assert!(sender.cancel_handoff(id).await.is_err());
    }
